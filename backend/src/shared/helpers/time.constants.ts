/**
 * Milliseconds in one second, for the durations APIs give in seconds.
 */
export const SECOND_MS = 1000;

/**
 * Milliseconds in one minute, for every duration counted in minutes.
 */
export const MINUTE_MS = 60 * SECOND_MS;

/**
 * Milliseconds in one hour, for every duration counted in hours.
 */
export const HOUR_MS = 60 * MINUTE_MS;

/**
 * Milliseconds in one day, for every duration counted in days.
 */
export const DAY_MS = 24 * HOUR_MS;
